/*
 * 시군구 철거비용 페이지의 설득 문구 변형.
 * 같은 뜻을 짧고 자연스러운 표현 여러 가지로 적어 두고, 지역 slug 와 섹션(또는 카드·단계 자리)마다 따로 고른다.
 * 지역 페이지끼리 본문이 겹치지 않게 하려는 것이며, 숫자·서비스 범위 같은 사실은 모든 표현에서 같다.
 */

function hash(text: string) {
  let value = 2166136261;
  for (let index = 0; index < text.length; index += 1) {
    value ^= text.charCodeAt(index);
    value = Math.imul(value, 16777619);
  }
  return value >>> 0;
}

export function pickFrom<T>(slug: string, section: string, options: readonly T[]): T {
  return options[hash(`${slug}:${section}`) % options.length];
}

export function pickOffset(slug: string, section: string, length: number) {
  return length > 0 ? hash(`${slug}:${section}:order`) % length : 0;
}

/* 자리마다 따로 고른다. sets[n][i] 는 i번째 자리의 n번째 표현이다. */
export function pickSlots<T>(slug: string, section: string, sets: readonly (readonly T[])[]): T[] {
  return sets[0].map((_, index) => pickFrom(slug, `${section}:${index}`, sets.map((set) => set[index])));
}

/* 목록 순서를 돌린다. 담긴 항목은 같다. */
export function rotate<T>(items: T[], by: number): T[] {
  if (items.length === 0) return items;
  const shift = by % items.length;
  return [...items.slice(shift), ...items.slice(0, shift)];
}

