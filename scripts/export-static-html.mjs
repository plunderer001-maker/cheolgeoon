import { appendFile, cp, mkdir, readFile, rm, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const rootDir = path.resolve(__dirname, "..");
const outputDir = path.join(rootDir, "static-site");
const clientDir = path.join(rootDir, "dist", "client");
const workerPath = path.join(rootDir, "dist", "server", "index.js");
const seoDataPath = path.join(rootDir, "data", "generated", "seo-pages.json");
const regionsDataPath = path.join(rootDir, "data", "generated", "regions.json");
const regionServiceDataPath = path.join(rootDir, "data", "generated", "region-service-pages.json");

// app/lib/seo-pages.ts 와 동일한 규칙. 잘림·중복 의도 페이지와 검토필요 대상은 내보내지 않고
// 기존 URL은 _redirects 로 301 처리한다.
const EXCLUDED_INTENTS = {
  비: "비용",
  단가: "비용",
  견적서: "견적",
};

function isPublishedSeoPage(page) {
  return !page.restricted && !(page.intent in EXCLUDED_INTENTS);
}

function encodeRoute(route) {
  return route
    .split("/")
    .map((segment) => encodeURIComponent(decodeURIComponent(segment)))
    .join("/");
}

function stripClientRuntime(html) {
  return html
    .replace(/<link\b[^>]*rel=["']modulepreload["'][^>]*>/gi, "")
    .replace(/<script\b[^>]*>[\s\S]*?<\/script>/gi, "")
    .replace(/\sdata-rsc-css-href="[^"]*"/gi, "");
}

function routeToFilePath(route) {
  if (route === "/") return path.join(outputDir, "index.html");

  const segments = route
    .split("/")
    .filter(Boolean)
    .map((segment) => decodeURIComponent(segment));

  return path.join(outputDir, ...segments, "index.html");
}

async function renderRoute(worker, route) {
  const url = `http://localhost${encodeRoute(route)}`;

  const response = await worker.fetch(
    new Request(url, {
      headers: { accept: "text/html" },
    }),
    {
      ASSETS: {
        fetch: async () => new Response("Not found", { status: 404 }),
      },
    },
    {
      waitUntil() {},
      passThroughOnException() {},
    },
  );

  if (!response.ok) {
    throw new Error(`Failed to render ${route}: ${response.status}`);
  }

  const contentType = response.headers.get("content-type") ?? "";
  if (!contentType.toLowerCase().startsWith("text/html")) {
    throw new Error(`Expected HTML for ${route}, received ${contentType}`);
  }

  return stripClientRuntime(await response.text());
}

async function writeRoute(worker, route) {
  const html = await renderRoute(worker, route);
  const filePath = routeToFilePath(route);
  await mkdir(path.dirname(filePath), { recursive: true });
  await writeFile(filePath, html, "utf8");
}

/**
 * 더 이상 생성하지 않는 서비스 페이지의 301 규칙.
 * - 잘림·중복 의도(-비, -단가, -견적서) → 같은 대상·작업유형의 canonical 의도 페이지
 * - 검토필요 대상(경찰서, 주유소 등)과 완파철거 → 서비스 허브
 */
function buildRedirects(seoPages, publishedSlugs) {
  const lines = [
    "# Generated by scripts/export-static-html.mjs — do not edit by hand.",
    "# Retired keyword-permutation pages redirect to their canonical page.",
  ];

  for (const page of seoPages) {
    if (isPublishedSeoPage(page)) continue;

    const from = encodeRoute(`/services/${page.slug}/`);
    let to = "/services/";

    const canonicalIntent = EXCLUDED_INTENTS[page.intent];
    if (canonicalIntent && !page.restricted) {
      const canonical = seoPages.find(
        (candidate) =>
          candidate.target === page.target &&
          candidate.service === page.service &&
          candidate.intent === canonicalIntent,
      );
      if (canonical && publishedSlugs.has(canonical.slug)) {
        to = encodeRoute(`/services/${canonical.slug}/`);
      }
    }

    lines.push(`${from} ${to} 301`);
  }

  // 기존 잘못된 링크 형태와 index.html 직접 접근 정리
  lines.push("/index.html / 301!");

  return `${lines.join("\n")}\n`;
}

const EXTRA_HEADERS = `
# Long-lived cache for versioned image assets
/images/*
  Cache-Control: public, max-age=31536000, immutable

# Security headers (site has no inline scripts or third-party embeds)
/*
  X-Content-Type-Options: nosniff
  X-Frame-Options: DENY
  Referrer-Policy: strict-origin-when-cross-origin
  Permissions-Policy: camera=(), microphone=(), geolocation=()
  Content-Security-Policy: default-src 'self'; img-src 'self' data:; style-src 'self' 'unsafe-inline'; font-src 'self' data:; frame-ancestors 'none'; base-uri 'self'; form-action 'self' https://naver.me https://form.naver.com
`;

async function main() {
  const seoData = JSON.parse(await readFile(seoDataPath, "utf8"));
  const regionsData = JSON.parse(await readFile(regionsDataPath, "utf8"));
  const regionServiceData = JSON.parse(await readFile(regionServiceDataPath, "utf8"));

  const publishedSeoPages = seoData.pages.filter(isPublishedSeoPage);
  const publishedSlugs = new Set(publishedSeoPages.map((page) => page.slug));

  const routes = [
    "/",
    "/services",
    ...publishedSeoPages.map((page) => `/services/${page.slug}`),
    "/regions",
    ...regionsData.regions.map((region) => `/regions/${region.slug}`),
    ...regionServiceData.pages.map((page) => `/regions/${page.slug}`),
  ];

  console.log(
    `Service pages: ${publishedSeoPages.length} published, ${
      seoData.pages.length - publishedSeoPages.length
    } retired (redirected)`,
  );

  await rm(outputDir, { recursive: true, force: true });
  await mkdir(outputDir, { recursive: true });
  await cp(clientDir, outputDir, { recursive: true });

  await appendFile(path.join(outputDir, "_headers"), EXTRA_HEADERS, "utf8");
  await writeFile(
    path.join(outputDir, "_redirects"),
    buildRedirects(seoData.pages, publishedSlugs),
    "utf8",
  );

  const workerUrl = pathToFileURL(workerPath);
  workerUrl.searchParams.set("export", `${process.pid}-${Date.now()}`);
  const { default: worker } = await import(workerUrl.href);

  const startedAt = Date.now();
  for (let index = 0; index < routes.length; index += 1) {
    await writeRoute(worker, routes[index]);

    const completed = index + 1;
    if (completed % 500 === 0 || completed === routes.length) {
      const elapsedSeconds = ((Date.now() - startedAt) / 1000).toFixed(1);
      console.log(`Exported ${completed}/${routes.length} pages in ${elapsedSeconds}s`);
    }
  }

  console.log(`Static HTML export complete: ${outputDir}`);
}

main().catch((error) => {
  console.error(error);
  process.exit(1);
});
