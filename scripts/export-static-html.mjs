import { appendFile, cp, mkdir, readFile, rm, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const rootDir = path.resolve(__dirname, "..");
const outputDir = path.join(rootDir, "static-site");
const clientDir = path.join(rootDir, "dist", "client");
const workerPath = path.join(rootDir, "dist", "server", "index.js");
const regionsDataPath = path.join(rootDir, "data", "generated", "regions.json");
const regionTopicDataPath = path.join(rootDir, "data", "generated", "region-service-pages.json");
const retiredRoutesPath = path.join(rootDir, "data", "generated", "retired-routes.json");

const SIDO_ORDER = ["서울", "경기", "인천", "부산", "대구", "광주", "대전", "울산", "강원", "충북", "충남", "전북", "전남", "경북", "경남", "제주"];
const DUPLICATE_SIDO_SHORT = "전남광주통합";

function encodeRoute(route) {
  return route
    .split("/")
    .map((segment) => encodeURIComponent(decodeURIComponent(segment)))
    .join("/");
}

/** 클라이언트 런타임 스크립트만 제거하고 JSON-LD(구조화 데이터)는 남긴다. */
function stripClientRuntime(html) {
  return html
    .replace(/<link\b[^>]*rel=["']modulepreload["'][^>]*>/gi, "")
    .replace(/<script\b(?![^>]*type=["']application\/ld\+json["'])[^>]*>[\s\S]*?<\/script>/gi, "")
    .replace(/\sdata-rsc-css-href="[^"]*"/gi, "");
}

function routeToFilePath(route) {
  if (route === "/") return path.join(outputDir, "index.html");

  const segments = route
    .split("/")
    .filter(Boolean)
    .map((segment) => decodeURIComponent(segment));

  return path.join(outputDir, ...segments, "index.html");
}

async function renderRoute(worker, route) {
  const url = `http://localhost${encodeRoute(route)}`;

  const response = await worker.fetch(
    new Request(url, {
      headers: { accept: "text/html" },
    }),
    {
      ASSETS: {
        fetch: async () => new Response("Not found", { status: 404 }),
      },
    },
    {
      waitUntil() {},
      passThroughOnException() {},
    },
  );

  if (!response.ok) {
    throw new Error(`Failed to render ${route}: ${response.status}`);
  }

  const contentType = response.headers.get("content-type") ?? "";
  if (!contentType.toLowerCase().startsWith("text/html")) {
    throw new Error(`Expected HTML for ${route}, received ${contentType}`);
  }

  return stripClientRuntime(await response.text());
}

async function writeRoute(worker, route) {
  const html = await renderRoute(worker, route);
  const filePath = routeToFilePath(route);
  await mkdir(path.dirname(filePath), { recursive: true });
  await writeFile(filePath, html, "utf8");
}

/**
 * 더 이상 생성하지 않는 URL 의 301 규칙. 와일드카드로 압축해 Netlify·Cloudflare Pages
 * (최대 2,100건) 어디서든 동작하도록 유지한다. 새 허브는 /guide/ 아래에 두어
 * 옛 /services/* 경로와 겹치지 않는다.
 * - /services/*(옛 대상별 서비스 페이지 13,720개) → 주제 허브
 * - /regions/:region/{옛 서비스}/ → 같은 지역의 주제 페이지
 * - /regions/전남광주통합-…/* (중복 시도 코드) → 대응 지역의 주제 페이지
 */
function buildRedirects({ retired, topics }) {
  const primaryTopic = topics[0];
  const hub = encodeRoute(`/guide/${primaryTopic.slug}/`);
  const lines = [
    "# Generated by scripts/export-static-html.mjs — do not edit by hand.",
    "# Retired pages redirect to the closest live page.",
    `/services/* ${hub} 301`,
  ];

  for (const { slug, counterpartSlug } of retired.duplicateRegions) {
    const target = counterpartSlug ? encodeRoute(`/regions/${counterpartSlug}/${primaryTopic.slug}/`) : "/regions/";
    lines.push(`${encodeRoute(`/regions/${slug}`)}/* ${target} 301`);
  }

  for (const serviceSlug of retired.retiredServiceSlugs) {
    lines.push(`/regions/:region/${encodeRoute(serviceSlug)}/ /regions/:region/${encodeRoute(primaryTopic.slug)}/ 301`);
  }

  lines.push("/index.html / 301");

  return `${lines.join("\n")}\n`;
}

const EXTRA_HEADERS = `
# Long-lived cache for versioned image assets
/images/*
  Cache-Control: public, max-age=31536000, immutable

# Security headers (site has no inline scripts or third-party embeds)
/*
  X-Content-Type-Options: nosniff
  X-Frame-Options: DENY
  Referrer-Policy: strict-origin-when-cross-origin
  Permissions-Policy: camera=(), microphone=(), geolocation=()
  Content-Security-Policy: default-src 'self'; img-src 'self' data:; style-src 'self' 'unsafe-inline'; font-src 'self' data:; frame-ancestors 'none'; base-uri 'self'; form-action 'self' https://naver.me https://form.naver.com
`;

async function main() {
  const regionsData = JSON.parse(await readFile(regionsDataPath, "utf8"));
  const regionTopicData = JSON.parse(await readFile(regionTopicDataPath, "utf8"));
  const retired = JSON.parse(await readFile(retiredRoutesPath, "utf8"));

  const regions = regionsData.regions.filter((region) => region.sidoShort !== DUPLICATE_SIDO_SHORT);
  const topics = regionTopicData.services;
  const sidoSlugs = SIDO_ORDER.filter((short) => regions.some((region) => region.sidoShort === short));

  const routes = [
    "/",
    "/guide",
    ...topics.map((topic) => `/guide/${topic.slug}`),
    ...topics.flatMap((topic) => sidoSlugs.map((sido) => `/guide/${topic.slug}/${sido}`)),
    "/regions",
    ...regions.map((region) => `/regions/${region.slug}`),
    ...regionTopicData.pages.map((page) => `/regions/${page.slug}`),
  ];

  console.log(
    `Routes: ${routes.length} (topics ${topics.length}, sido hubs ${sidoSlugs.length * topics.length}, regions ${regions.length}, region topic pages ${regionTopicData.pages.length})`,
  );

  await rm(outputDir, { recursive: true, force: true });
  await mkdir(outputDir, { recursive: true });
  await cp(clientDir, outputDir, { recursive: true });

  await appendFile(path.join(outputDir, "_headers"), EXTRA_HEADERS, "utf8");
  const redirects = buildRedirects({ retired, topics });
  await writeFile(path.join(outputDir, "_redirects"), redirects, "utf8");
  console.log(`Redirect rules: ${redirects.split("\n").filter((line) => line && !line.startsWith("#")).length}`);

  const workerUrl = pathToFileURL(workerPath);
  workerUrl.searchParams.set("export", `${process.pid}-${Date.now()}`);
  const { default: worker } = await import(workerUrl.href);

  const startedAt = Date.now();
  for (let index = 0; index < routes.length; index += 1) {
    await writeRoute(worker, routes[index]);

    const completed = index + 1;
    if (completed % 200 === 0 || completed === routes.length) {
      const elapsedSeconds = ((Date.now() - startedAt) / 1000).toFixed(1);
      console.log(`Exported ${completed}/${routes.length} pages in ${elapsedSeconds}s`);
    }
  }

  console.log(`Static HTML export complete: ${outputDir}`);
}

main().catch((error) => {
  console.error(error);
  process.exit(1);
});
